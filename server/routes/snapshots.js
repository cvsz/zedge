import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { CFError } from '../cf.js';
import { HttpError, bad } from '../errors.js';
import { KINDS } from './rules.js';

const SNAP_RE = /^\d{8}T\d{6}Z-[a-f0-9]{6}$/;
const KEEP_SNAPSHOTS = 50;
const RULE_FIELDS = ['action', 'expression', 'description', 'action_parameters', 'ratelimit', 'enabled'];
const DNS_FIELDS = ['type', 'name', 'content', 'proxied', 'ttl', 'priority', 'comment', 'data'];
// Zone settings that are safe and useful to copy between zones.
export const CLONEABLE = ['ssl', 'min_tls_version', 'tls_1_3', 'always_use_https', 'automatic_https_rewrites', 'http3', 'brotli', 'early_hints', 'browser_cache_ttl', 'security_level', 'challenge_ttl', 'opportunistic_encryption', 'websockets', 'ipv6', 'email_obfuscation', 'hotlink_protection'];

const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined && o[k] !== null).map((k) => [k, o[k]]));
const stable = (v) => JSON.stringify(v, (k, x) => (x && typeof x === 'object' && !Array.isArray(x) ? Object.fromEntries(Object.keys(x).sort().map((kk) => [kk, x[kk]])) : x));
const dnsId = (r) => `${r.type} ${r.name} ${r.content || stable(r.data)}${r.priority !== undefined ? ` ${r.priority}` : ''}`;
const ruleId = (r) => `${r.description || ''}|${r.action}|${r.expression}`;
const normRule = (r) => pick({ enabled: true, ...r }, RULE_FIELDS);

/** Compare a snapshot with the live state. Pure function, easy to test. */
export function diffConfig(snap, live) {
  const out = { dns: { added: [], removed: [], changed: [] }, rules: {} };
  const sMap = new Map(snap.dns.map((r) => [dnsId(r), r]));
  const lMap = new Map(live.dns.map((r) => [dnsId(r), r]));
  for (const [id, r] of sMap) {
    const l = lMap.get(id);
    if (!l) out.dns.removed.push(r); // in the snapshot, gone now
    else if (!!l.proxied !== !!r.proxied || (l.ttl || 1) !== (r.ttl || 1)) out.dns.changed.push({ before: r, after: l, id: l.id });
  }
  for (const [id, r] of lMap) if (!sMap.has(id)) out.dns.added.push(r); // new since the snapshot
  const phases = new Set([...Object.keys(snap.rules), ...Object.keys(live.rules)]);
  for (const ph of phases) {
    const a = new Map((snap.rules[ph] || []).map((r) => [ruleId(r), normRule(r)]));
    const b = new Map((live.rules[ph] || []).map((r) => [ruleId(r), normRule(r)]));
    const d = { added: [], removed: [], changed: [] };
    for (const [id, r] of a) { if (!b.has(id)) d.removed.push(r); else if (stable(b.get(id)) !== stable(r)) d.changed.push({ before: r, after: b.get(id) }); }
    for (const [id, r] of b) if (!a.has(id)) d.added.push(r);
    if (d.added.length || d.removed.length || d.changed.length) out.rules[ph] = d;
  }
  return out;
}

const q = (s) => JSON.stringify(String(s));
const tfName = (r, i) => `${r.type.toLowerCase()}_${r.name.replace(/[^a-z0-9]+/gi, '_').replace(/^_+|_+$/g, '').toLowerCase() || 'root'}_${i}`;
/** Terraform for DNS records (provider v4 resource name; rename for v5 if you use it). */
export function toTerraform(zoneName, dns) {
  const simple = dns.filter((r) => r.content !== undefined);
  const lines = [`# Generated by Zedge for ${zoneName}. Uses the cloudflare_record resource (provider v4).`, 'variable "zone_id" { type = string }', ''];
  simple.forEach((r, i) => {
    lines.push(`resource "cloudflare_record" ${q(tfName(r, i))} {`, '  zone_id = var.zone_id', `  name    = ${q(r.name)}`, `  type    = ${q(r.type)}`, `  content = ${q(r.content)}`, `  ttl     = ${r.proxied ? 1 : (r.ttl || 1)}`);
    if (r.priority !== undefined) lines.push(`  priority = ${Number(r.priority)}`);
    lines.push(`  proxied = ${r.proxied ? 'true' : 'false'}`, '}', '');
  });
  const skipped = dns.length - simple.length;
  if (skipped) lines.push(`# ${skipped} structured record(s) (SRV, CAA, ...) were not exported; use the JSON export for them.`);
  return lines.join('\n');
}

/**
 * Terraform JSON syntax (.tf.json) for DNS records and rulesets. The JSON syntax lets rule blocks reuse
 * Cloudflare's own field names, so nothing has to be re-spelled. Best effort: run `terraform validate`
 * and `terraform plan` before applying, because provider schemas change between versions.
 */
export function toTerraformJson(zoneName, dns, rules) {
  const resource = { cloudflare_record: {}, cloudflare_ruleset: {} };
  dns.filter((r) => r.content !== undefined).forEach((r, i) => {
    resource.cloudflare_record[tfName(r, i)] = { zone_id: '${var.zone_id}', name: r.name, type: r.type, content: r.content, ttl: r.proxied ? 1 : (r.ttl || 1), proxied: !!r.proxied, ...(r.priority !== undefined ? { priority: Number(r.priority) } : {}) };
  });
  for (const [phase, list] of Object.entries(rules)) {
    resource.cloudflare_ruleset[phase] = {
      zone_id: '${var.zone_id}', name: `${zoneName} ${phase}`, kind: 'zone', phase,
      rules: list.map((r) => pick(r, ['action', 'expression', 'description', 'enabled', 'action_parameters', 'ratelimit']))
    };
  }
  if (!Object.keys(resource.cloudflare_ruleset).length) delete resource.cloudflare_ruleset;
  if (!Object.keys(resource.cloudflare_record).length) delete resource.cloudflare_record;
  return JSON.stringify({ '//': `Generated by Zedge for ${zoneName}. Best effort: run terraform validate and plan before applying.`, variable: { zone_id: { type: 'string' } }, resource }, null, 2);
}

export function registerSnapshots(app, ctx) {
  const { cf, config, wrap, need } = ctx;
  const root = path.join(config.dataDir, 'snapshots');
  const dirFor = (zid) => path.join(root, zid);
  const fileFor = (zid, sid) => {
    if (!SNAP_RE.test(sid)) throw bad('Invalid snapshot id');
    return path.join(dirFor(zid), `${sid}.json`);
  };

  async function entry(zid, phase) {
    try { return (await cf.get(`/zones/${zid}/rulesets/phases/${phase}/entrypoint`)).result; } catch (e) {
      if (e instanceof CFError && e.status === 404) return null;
      throw e;
    }
  }

  async function capture(zid) {
    const zone = (await cf.get(`/zones/${zid}`)).result;
    const dns = (await cf.listAll(`/zones/${zid}/dns_records`)).map((r) => ({ id: r.id, ...pick(r, DNS_FIELDS) }));
    const rules = {};
    for (const k of Object.values(KINDS)) {
      const e = await entry(zid, k.phase);
      if (e && e.rules && e.rules.length) rules[k.phase] = e.rules.map((r) => ({ id: r.id, ...normRule(r) }));
    }
    return { zone: zone.name, dns, rules };
  }

  const list = (zid) => {
    try {
      return fs.readdirSync(dirFor(zid)).filter((f) => f.endsWith('.json')).sort().reverse().map((f) => {
        const s = JSON.parse(fs.readFileSync(path.join(dirFor(zid), f), 'utf8'));
        return { id: s.id, createdAt: s.createdAt, by: s.by, note: s.note, dnsCount: s.dns.length, ruleCount: Object.values(s.rules).reduce((a, r) => a + r.length, 0) };
      });
    } catch { return []; }
  };
  const load = (zid, sid) => {
    try { return JSON.parse(fs.readFileSync(fileFor(zid, sid), 'utf8')); } catch (e) {
      if (e instanceof HttpError) throw e;
      throw new HttpError(404, 'No such snapshot');
    }
  };

  app.get('/api/zones/:zid/snapshots', need('read'), wrap(async (req, res) => { res.json({ snapshots: list(req.params.zid) }); }));

  app.post('/api/zones/:zid/snapshots', need('read'), wrap(async (req, res) => {
    const snap = await capture(req.params.zid);
    const now = new Date();
    const id = `${now.toISOString().replace(/[-:]/g, '').replace(/\.\d+/, '')}-${crypto.randomBytes(3).toString('hex')}`;
    const full = { id, createdAt: now.toISOString(), by: req.user.name, note: String((req.body && req.body.note) || '').slice(0, 200), ...snap };
    fs.mkdirSync(dirFor(req.params.zid), { recursive: true, mode: 0o700 });
    fs.writeFileSync(fileFor(req.params.zid, id), JSON.stringify(full), { mode: 0o600 });
    for (const old of list(req.params.zid).slice(KEEP_SNAPSHOTS)) fs.rmSync(fileFor(req.params.zid, old.id), { force: true });
    res.status(201).json({ id, dnsCount: full.dns.length });
  }));

  app.get('/api/zones/:zid/snapshots/:sid/diff', need('read'), wrap(async (req, res) => {
    const snap = load(req.params.zid, req.params.sid);
    res.json({ snapshot: { id: snap.id, createdAt: snap.createdAt }, diff: diffConfig(snap, await capture(req.params.zid)) });
  }));

  app.delete('/api/zones/:zid/snapshots/:sid', need('snapshots.write'), wrap(async (req, res) => {
    load(req.params.zid, req.params.sid);
    fs.rmSync(fileFor(req.params.zid, req.params.sid), { force: true });
    res.json({ ok: true });
  }));

  /** Put the zone back the way the snapshot had it. Without confirm: true this only returns the plan. */
  app.post('/api/zones/:zid/snapshots/:sid/restore', need('snapshots.write'), wrap(async (req, res) => {
    const zid = req.params.zid;
    const b = req.body || {};
    const scope = ['dns', 'rules', 'all'].includes(b.scope) ? b.scope : 'all';
    const snap = load(zid, req.params.sid);
    const live = await capture(zid);
    const d = diffConfig(snap, live);
    const plan = {
      dns: scope === 'rules' ? null : { create: d.dns.removed.length, update: d.dns.changed.length, delete: b.deleteExtra ? d.dns.added.length : 0, keepExtra: b.deleteExtra ? 0 : d.dns.added.length },
      rules: scope === 'dns' ? null : Object.keys(d.rules)
    };
    if (b.confirm !== true) return res.json({ applied: false, plan });
    const failed = [];
    const attempt = async (label, fn) => { try { await fn(); } catch (e) { failed.push({ what: label, error: e.message }); } };
    if (plan.dns) {
      for (const r of d.dns.removed) await attempt(`create ${r.type} ${r.name}`, () => cf.post(`/zones/${zid}/dns_records`, pick(r, DNS_FIELDS)));
      for (const c of d.dns.changed) await attempt(`update ${c.before.type} ${c.before.name}`, () => cf.patch(`/zones/${zid}/dns_records/${c.id}`, { proxied: c.before.proxied, ttl: c.before.ttl }));
      if (b.deleteExtra) for (const r of d.dns.added) await attempt(`delete ${r.type} ${r.name}`, () => cf.del(`/zones/${zid}/dns_records/${r.id}`));
    }
    if (plan.rules) {
      for (const phase of plan.rules) await attempt(`rules ${phase}`, () => cf.put(`/zones/${zid}/rulesets/phases/${phase}/entrypoint`, { rules: (snap.rules[phase] || []).map(normRule) }));
    }
    res.json({ applied: true, plan, failed });
  }));

  // ---- export: JSON (full config) or Terraform (DNS) ----
  app.get('/api/zones/:zid/export', need('read'), wrap(async (req, res) => {
    const format = String(req.query.format || 'json');
    if (!['json', 'terraform', 'terraform-json'].includes(format)) throw bad('format must be json, terraform or terraform-json');
    const snap = await capture(req.params.zid);
    if (format === 'terraform-json') return res.type('application/json').set('Content-Disposition', `attachment; filename="${snap.zone}.tf.json"`).send(toTerraformJson(snap.zone, snap.dns, snap.rules));
    if (format === 'terraform') return res.type('text/plain').set('Content-Disposition', `attachment; filename="${snap.zone}.tf"`).send(toTerraform(snap.zone, snap.dns));
    return res.type('application/json').set('Content-Disposition', `attachment; filename="${snap.zone}.json"`).send(JSON.stringify({ exportedAt: new Date().toISOString(), ...snap }, null, 2));
  }));

  // ---- clone this zone's settings onto another zone ----
  app.post('/api/zones/:zid/clone-settings', need('zone.write'), wrap(async (req, res) => {
    const from = String((req.body && req.body.from) || '');
    if (!/^[A-Za-z0-9_-]{6,64}$/.test(from)) throw bad('Choose a zone to copy from');
    if (from === req.params.zid) throw bad('Choose a different zone to copy from');
    await ctx.assertZone(from, req);
    const src = (await cf.get(`/zones/${from}/settings`)).result || [];
    const dst = (await cf.get(`/zones/${req.params.zid}/settings`)).result || [];
    const have = new Map(dst.map((s) => [s.id, s.value]));
    const applied = [];
    const failed = [];
    for (const s of src.filter((x) => CLONEABLE.includes(x.id) && have.has(x.id) && stable(have.get(x.id)) !== stable(x.value))) {
      try { await cf.patch(`/zones/${req.params.zid}/settings/${s.id}`, { value: s.value }); applied.push(s.id); } catch (e) { failed.push({ setting: s.id, error: e.message }); }
    }
    res.json({ applied, failed });
  }));
}
